public class Ejercicio04_NumerosParesWhile {

    public static void main(String[] args) {
        //Realizar un programa que imprima los 
        //números pares del 2 al 100 utilizando ciclos while.
        int num = 2;

        while (num <= 100) {
            System.out.println(num);
            num += 2;
        }

    }

}
