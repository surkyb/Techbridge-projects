    /**
    * Evento del botón "Calcular".
    * Calcula la nota final del estudiante y determina si está aprobado o reprobado.
    * También valida los rangos de cada calificación.
    */
    private void jbtCalcularActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbtCalcularActionPerformed
        try {
        double practicas = Double.parseDouble(txtPracticas.getText());
        double parciales = Double.parseDouble(txtParciales.getText());
        double asignaciones = Double.parseDouble(txtAsignaciones.getText());
        double examen = Double.parseDouble(txtExamen.getText());

        // Validar rangos
        if (practicas < 0 || practicas > 40 ||
            parciales < 0 || parciales > 20 ||
            asignaciones < 0 || asignaciones > 20 ||
            examen < 0 || examen > 20) {

            javax.swing.JOptionPane.showMessageDialog(this, "Valores fuera de rango");
            return;
        }

        // Calcular total
        double total = practicas + parciales + asignaciones + examen;

        // Determinar estado
        if (total >= 60) {
        txtResultado.setText("APROBADO - " + total + " puntos");
        txtResultado.setBackground(java.awt.Color.GREEN);
        txtResultado.setForeground(java.awt.Color.BLACK);
    } else {
        txtResultado.setText("REPROBADO - " + total + " puntos");
        txtResultado.setBackground(java.awt.Color.RED);
        txtResultado.setForeground(java.awt.Color.WHITE);
    }

    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Ingrese solo números en las notas");
    }
    }//GEN-LAST:event_jbtCalcularActionPerformed

