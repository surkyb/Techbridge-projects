    /**
    * Evento del botón "Siguiente".
    * Valida los datos personales del estudiante y, si son correctos,
    * cambia a la pestaña de calificaciones.
    */
    private void jbtSiguienteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbtSiguienteActionPerformed
        String nombre = txtNombre.getText();
        String matricula = txtMatricula.getText();
        String carrera = txtCarrera.getText();
         // Validar campos vacíos
        if (nombre.isEmpty() || matricula.isEmpty() || carrera.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Complete todos los campos");
            return;
        }
        //Validar que el nombre solo contenga letras
        if (!nombre.matches("[a-zA-ZáéíóúÁÉÍÓÚñÑ ]+")) {
            javax.swing.JOptionPane.showMessageDialog(this, "Nombre inválido");
            return;
        }
         // Validar que la carrera solo contenga letras
        if (!carrera.matches("[a-zA-ZáéíóúÁÉÍÓÚñÑ ]+")) {
            javax.swing.JOptionPane.showMessageDialog(this, "Carrera inválida");
            return;
        }
         // Validar que la matrícula solo tenga números y guiones
        if (!matricula.matches("[0-9-]+")) {
            javax.swing.JOptionPane.showMessageDialog(this, "Matrícula inválida");
            return;
        }
        // Si todo está bien cambiar de pestaña
        jTabbedPane1.setSelectedIndex(1);
    }//GEN-LAST:event_jbtSiguienteActionPerformed

