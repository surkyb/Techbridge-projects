    private void btnRaizActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRaizActionPerformed
        validarCampos();
        
        
        RaizYExponente raiz = new RaizYExponente();
        
        double valor1 = Double.parseDouble(txtvalorRaiz.getText());
        
        double resultado = raiz.raiz(valor1);
          
          txtResultado.setText(String.valueOf(resultado));
    }//GEN-LAST:event_btnRaizActionPerformed

    private void btnExpoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExpoActionPerformed
        validarCampos();
        
        
         RaizYExponente raiz = new RaizYExponente();
        
        double valor1 = Double.parseDouble(txtValorExpo.getText());
        double valor2 = Double.parseDouble(txtExpo.getText());
        
        double resultado = raiz.exponente(valor1, valor2);
          
          txtResultado.setText(String.valueOf(resultado));
    }//GEN-LAST:event_btnExpoActionPerformed

