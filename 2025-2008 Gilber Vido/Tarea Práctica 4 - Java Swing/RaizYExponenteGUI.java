    private void validarCampos() {
        if (txtvalorRaiz.getText().trim().length() <= 0) {
            JOptionPane.showMessageDialog(null, "Por favor ingresar el valor 1");
            txtvalorRaiz.requestFocus();
        } else if (txtValorExpo.getText().trim().length() <= 0) {
            JOptionPane.showMessageDialog(null, "Por favor ingresar el valor 1");
            txtValorExpo.requestFocus();
        } else if (txtExpo.getText().trim().length() <= 0) {
            JOptionPane.showMessageDialog(null, "Por favor ingresar el valor 1");
            txtExpo.requestFocus();
        }
    }

    private void limpiarCampos() {
        txtvalorRaiz.setText("");
        txtResultado.setText("");
        txtValorExpo.setText("");
        txtExpo.setText("");
    }

