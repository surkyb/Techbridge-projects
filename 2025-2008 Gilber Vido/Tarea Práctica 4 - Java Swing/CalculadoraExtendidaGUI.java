    private void bntSumarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bntSumarActionPerformed
        validarCampos();
        
        /**
         * Aqui creo un objeto para poder utilizar el metodo de la clase 
         * calculadora
         */
        Calculadora cal = new Calculadora();
        
        double valor1 = Double.parseDouble(txtValor1.getText());
        double valor2 = Double.parseDouble(txtValor2.getText());
        
        double resultado = cal.sumar(valor1, valor2);
        
        /**
         * Aqui paso a enviar el resultado al txt correspondiente
         * (convirtiendolo en string)
         */
        txtResultado.setText(String.valueOf(resultado));
    }//GEN-LAST:event_bntSumarActionPerformed

