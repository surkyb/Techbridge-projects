    private void bntDividirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bntDividirActionPerformed
        validarCampos();
        
        /**
         * Aqui creo un objeto para poder utilizar el metodo de la clase 
         * calculadora
         */
        Calculadora calDiv = new Calculadora();
        
        double valor1 = Double.parseDouble(txtValor1.getText());
        double valor2 = Double.parseDouble(txtValor2.getText());
        
        /**
         * Verificamos de que no se este dividiendo por 0
         */
        if ( valor2 !=0 ){
            double resultado = calDiv.dividir(valor1, valor2);
            txtResultado.setText(String.valueOf(resultado));
        }
        else{
            String resultado = "No se puede dividir en 0";
            txtResultado.setText(String.valueOf(resultado));
        }
    }//GEN-LAST:event_bntDividirActionPerformed

    private void txtValor1KeyTyped(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtValor1KeyTyped
        char numeros = evt.getKeyChar();
        if ((numeros < '0' || numeros > '9') && (numeros < ',' || numeros > '.')) {
            JOptionPane.showMessageDialog(null, "por favor agregar numeros");
            evt.consume();
        }
    }//GEN-LAST:event_txtValor1KeyTyped

