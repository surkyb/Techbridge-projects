    /**
     * Este metodo es para poder validar que los txt no esten 
     * vacios a la hora de ejecutar cualquier operacion
     */
    private void validarCampos()
    {
        if(txtValor1.getText().trim().length()<= 0){
            JOptionPane.showMessageDialog(null,"Por favor ingresar el valor 1");
            txtValor1.requestFocus();
        } else if(txtValor2.getText().trim().length()<= 0){
            JOptionPane.showMessageDialog(null,"Por favor ingresar el valor 2");
            txtValor2.requestFocus();
        }
    }
    
